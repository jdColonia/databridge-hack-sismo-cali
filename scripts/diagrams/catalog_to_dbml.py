#!/usr/bin/env python3
"""Generate a DBML data diagram from Unity Catalog for import into ChartDB.

ChartDB has no Databricks connector, so the project's source of truth is a
DBML file versioned in Git. This script reads table metadata through the
Databricks CLI (Unity Catalog REST API, so no SQL warehouse is needed) and
writes DBML that ChartDB can import (Actions > Import > DBML).

What it emits:
  - one Table per Delta table whose name matches <layer>_<team>_*
  - Databricks column types as-is (bigint, string, double, boolean, ...)
  - `not null` for non-nullable columns, `note` from column/table COMMENTs
  - `pk` and Refs from informational PRIMARY KEY / FOREIGN KEY constraints
  - optional logical Refs (medallion lineage) from a JSON file
  - one TableGroup per layer (ChartDB ignores TableGroups; dbdiagram and
    other DBML viewers use them)

Usage:
  python3 scripts/diagrams/catalog_to_dbml.py \
      --profile el-equipo --catalog workspace --schema dev_<usuario> \
      --team el_equipo --relaciones docs/diagrams/relaciones_logicas.json \
      --out docs/diagrams/catalogo_dev.dbml

Only the Python standard library and the Databricks CLI are required.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys

LAYERS = ("bronze", "silver", "gold")
# Header colors per layer. ChartDB drops them on import; other DBML viewers use them.
LAYER_COLORS = {"bronze": "#B87333", "silver": "#8A8D91", "gold": "#D4A017"}


def run_cli(args: list[str], profile: str) -> object:
    cmd = ["databricks", *args, "-p", profile, "-o", "json"]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"Databricks CLI failed: {' '.join(cmd)}\n{res.stderr.strip()}")
    return json.loads(res.stdout or "null")


def q(text: str) -> str:
    """Quote a DBML string literal."""
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", " ") + "'"


def ident(name: str) -> str:
    """Quote identifiers that are not plain words."""
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) else f'"{name}"'


def layer_of(table: str, team: str) -> str | None:
    for layer in LAYERS:
        if table.startswith(f"{layer}_{team}_"):
            return layer
    return None


def build(tables: list[dict], team: str, catalog: str, schema: str,
          relaciones: list[dict]) -> str:
    tables = sorted(
        (t for t in tables if layer_of(t["name"], team)),
        key=lambda t: (LAYERS.index(layer_of(t["name"], team)), t["name"]),
    )
    if not tables:
        sys.exit(f"No tables named <layer>_{team}_* in {catalog}.{schema}")

    names = {t["name"] for t in tables}
    out: list[str] = []
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    out.append(f"// Generated by scripts/diagrams/catalog_to_dbml.py from {catalog}.{schema} on {stamp}.")
    out.append("// Do not edit by hand: change the notebooks or the table COMMENTs and regenerate.")
    out.append("")
    out.append(f"Project {ident(team + '_medallion')} {{")
    out.append("  database_type: 'Generic'")
    out.append(f"  Note: {q(f'Arquitectura medallion de {team} en {catalog}.{schema} (Databricks Unity Catalog, Delta).')}")
    out.append("}")
    out.append("")

    refs: list[str] = []
    for t in tables:
        layer = layer_of(t["name"], team)
        pk_cols: set[str] = set()
        for c in t.get("table_constraints") or []:
            pk = c.get("primary_key_constraint")
            if pk:
                pk_cols.update(pk.get("child_columns", []))
            fk = c.get("foreign_key_constraint")
            if fk:
                parent = fk["parent_table"].split(".")[-1]
                for child_col, parent_col in zip(fk["child_columns"], fk["parent_columns"]):
                    refs.append(
                        f"Ref {ident(fk['name'])}: {ident(t['name'])}.{ident(child_col)} > "
                        f"{ident(parent)}.{ident(parent_col)}"
                    )
        out.append(f"Table {ident(t['name'])} [headercolor: {LAYER_COLORS[layer]}] {{")
        for col in sorted(t.get("columns", []), key=lambda c: c.get("position", 0)):
            settings = []
            if col["name"] in pk_cols:
                settings.append("pk")
            if col.get("nullable") is False and col["name"] not in pk_cols:
                settings.append("not null")
            if col.get("comment"):
                settings.append(f"note: {q(col['comment'])}")
            typ = (col.get("type_text") or col.get("type_name") or "string").lower()
            typ = ident(typ) if re.fullmatch(r"[a-z_][a-z0-9_]*", typ) else f'"{typ}"'
            suffix = f" [{', '.join(settings)}]" if settings else ""
            out.append(f"  {ident(col['name'])} {typ}{suffix}")
        note = t.get("comment") or f"Capa {layer}."
        out.append(f"  Note: {q(note)}")
        out.append("}")
        out.append("")

    for r in relaciones:
        frm_t, frm_c = r["from"].split(".")
        to_t, to_c = r["to"].split(".")
        if frm_t in names and to_t in names:
            label = f" // {r['note']}" if r.get("note") else ""
            refs.append(
                f"Ref: {ident(frm_t)}.{ident(frm_c)} {r.get('type', '-')} "
                f"{ident(to_t)}.{ident(to_c)}{label}"
            )

    if refs:
        out.append("// Relaciones: FK informativas de Unity Catalog y linaje logico entre capas.")
        out.extend(refs)
        out.append("")

    for layer in LAYERS:
        members = [t["name"] for t in tables if layer_of(t["name"], team) == layer]
        if members:
            out.append(f"TableGroup {layer} [color: {LAYER_COLORS[layer]}] {{")
            out.extend(f"  {ident(m)}" for m in members)
            out.append("}")
            out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--profile", default="el-equipo")
    ap.add_argument("--catalog", default="workspace")
    ap.add_argument("--schema", required=True, help="default (prod) o dev_<usuario> (desarrollo)")
    ap.add_argument("--team", default="el_equipo")
    ap.add_argument("--relaciones", help="JSON con relaciones logicas [{from, to, type, note}]")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    tables = run_cli(["tables", "list", a.catalog, a.schema], a.profile) or []
    relaciones = []
    if a.relaciones:
        with open(a.relaciones, encoding="utf-8") as fh:
            relaciones = json.load(fh)
    dbml = build(tables, a.team, a.catalog, a.schema, relaciones)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(dbml)
    print(f"Escrito {a.out}")


if __name__ == "__main__":
    main()
